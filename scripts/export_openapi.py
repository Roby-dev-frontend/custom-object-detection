#!/usr/bin/env python3
"""Writes openapi.yaml, the description of the backend's API.

    python3 scripts/export_openapi.py
    python3 scripts/export_openapi.py --url https://192.168.1.200:8000/openapi.json
    python3 scripts/export_openapi.py --out docs/openapi.yaml

WHERE THE CONTENT COMES FROM
----------------------------
The HTTP routes are read from the running server's /openapi.json, which FastAPI
builds from the routes in server_fastapi.py themselves. Nothing here is typed by
hand, so the file cannot say something the code does not. That is also why the
server has to be running, and running the CURRENT code: restart it after adding
or changing a route, then run this script.

OpenAPI cannot describe WebSockets, so the four stream routes are added under
the top-level key `x-websockets`, from the table below. That table is the one
part written by hand: when a WebSocket route is added or its parameters change,
change it here too.

The server uses a self-signed certificate, so the certificate is not checked
(the request goes to this machine, or to an address given with --url).
"""

import argparse
import json
import os
import ssl
import sys
import urllib.request

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_URL = "https://localhost:8000/openapi.json"
DEFAULT_OUT = os.path.join(os.path.dirname(HERE), "openapi.yaml")

# Same for every stream: the session cookie is checked on the handshake and a
# refused connection is closed with code 4401.
WEBSOCKETS = {
    "/video_ws": {
        "summary": "The video of the server's camera, one frame per request.",
        "direction": "server -> page, a frame at a time, only when the page asks",
        "query": {"client": "id of the viewing page", "buffer": "seconds of footage to keep, 0 drops late frames (default 0)"},
        "source": "server_fastapi.py, video_ws",
    },
    "/camera_feed": {
        "summary": "A device uploads its own camera, for the others to watch.",
        "direction": "page -> server, JPEG frames",
        "query": {"client": "id of the publishing page"},
        "source": "server_fastapi.py, camera_feed",
    },
    "/detect_ws": {
        "summary": "A page sends its own frames and gets detections (or text) back.",
        "direction": "page -> server frames; server -> page messages",
        "query": {
            "client": "id of the page (cut to 64 characters)",
            "save": "0 = show only, anything else = also save to the strip",
            "mode": "text = text reading instead of objects",
        },
        "source": "server_fastapi.py, detect_ws",
    },
    "/camera_detect_ws": {
        "summary": "Detect (and save) from the server's own camera: nothing is uploaded.",
        "direction": "server -> page: only 'ready' and 'saved'",
        "query": {
            "save": "0 = show only, anything else = also save to the strip",
            "mode": "text = text reading instead of objects",
        },
        "source": "server_fastapi.py, camera_detect_ws",
    },
}


def fetch(url: str) -> dict:
    context = ssl.create_default_context()
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    try:
        with urllib.request.urlopen(url, context=context, timeout=15) as response:
            return json.load(response)
    except OSError as error:
        sys.exit(f"Could not read {url}: {error}\nIs the server running? "
                 "Try --url http://... if it runs without HTTPS.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Write openapi.yaml from the running server.")
    parser.add_argument("--url", default=DEFAULT_URL, help=f"default {DEFAULT_URL}")
    parser.add_argument("--out", default=DEFAULT_OUT, help="default openapi.yaml in the project folder")
    args = parser.parse_args()

    spec = fetch(args.url)
    spec["info"] = {
        "title": "Telecamera API",
        "description": (
            "Every route except POST /login needs a logged-in session (cookie from "
            "POST /login); the administration routes also need an administrator. "
            "Generated by scripts/export_openapi.py -- do not edit by hand. "
            "WebSocket routes are under x-websockets."
        ),
        "version": spec.get("info", {}).get("version", "0.1.0"),
    }
    spec["x-websockets"] = {
        path: {"authentication": "session cookie and page origin checked on the handshake; refused with close code 4401", **entry}
        for path, entry in WEBSOCKETS.items()
    }
    with open(args.out, "w", encoding="utf-8") as handle:
        yaml.safe_dump(spec, handle, sort_keys=False, allow_unicode=True, width=100)
    print(f"{len(spec['paths'])} paths + {len(WEBSOCKETS)} WebSocket routes -> {args.out}")


if __name__ == "__main__":
    main()
